"""Tables of the G-C2.1 verdict from the return package (after the run; not under the stamp).

    python -I audit/c2_write_verdict.py RECORDS AUDIT LISTING OUT.md

RECORDS is records/c2/return, AUDIT records/c2/audit (written by audit/c2_recompute.py), LISTING
records/c2/return_listing.txt (the archive's listing, times in CST). The script formats the numbers of the returned
records and of the author's recomputation. Beyond what the stamped evaluation wrote, it computes from the returned
files only:
  - medians, 90th percentiles and counts of the distance from the curve and of the other readings by level, by
    yield stress, for single members and for the tested members overall, and the composition of each run's tail
    (the pairs above its 90th percentile), from the per-pair rows of verdict.json, with the quantile rule of
    c2/evaluate.py (_quantile);
  - Pearson's correlation of the distance at 8 mm with the yield stress, over the 64 held-out members;
  - the norm of the predicted unknowns against the label's, and the largest predicted unknown in size;
  - mean losses, epoch times and durations from the histories and logs.
"""
import json
import pathlib
import re
import sys
from datetime import datetime

import numpy as np

LEVELS = (0.5, 1.0, 2.0, 3.0, 4.0, 6.0, 8.0)
RUNS = [("label_free", s) for s in "012"] + [("supervised_64", s) for s in "012"]
TESTED = ("tested_BJ_T1_preloaded", "tested_BJ_T1_snug", "tested_BJ_T2_preloaded", "tested_BJ_T2_snug")
FY_SPLIT = 300.0
STEPS_ALL = 3 * 102400 + 3 * 12800          # the steps of the six runs, as in RUNBOOK_C2.md, section 3
READ = ("F_err", "abs_F_err", "bound", "e_err", "F_sigma_err", "gap", "iou_contact", "iou_plastic", "bolt_err",
        "u_rel_l2")


def quantile(v, q: float) -> float:
    """c2/evaluate.py's _quantile: np.quantile, infinite when an infinite order statistic has a positive weight."""
    v = np.asarray(v, dtype=float)
    s = np.sort(v)
    h = (s.size - 1) * q
    lo = int(np.floor(h))
    nxt, t = min(lo + 1, s.size - 1), h - lo
    for x, weight in ((s[lo], 1.0 - t), (s[nxt], t)):
        if np.isinf(x) and weight > 0:
            return float(x)
    big = np.finfo(float).max / 4
    return float(np.quantile(np.where(np.isinf(v), np.sign(v) * big, v), q))


def pct(x, d=1, sign=False):
    if np.isinf(x):
        return "infinite"
    y = 100 * x
    if abs(y) >= 1000:
        return f"{y:+,.0f}%" if sign else f"{y:,.0f}%"
    return f"{y:+.{d}f}%" if sign else f"{y:.{d}f}%"


def sci(x):
    return "0" if x == 0 else f"{x:.1e}"


def span(xs, f):
    lo, hi = format(min(xs), f), format(max(xs), f)
    return lo if lo == hi else f"{lo} to {hi}"


def name(arm, s):
    return f"{arm} s{s}"


def main(rec: pathlib.Path, aud: pathlib.Path, listing: pathlib.Path, out: pathlib.Path) -> None:
    v = json.loads((rec / "verdict.json").read_text())
    man = json.loads((rec / "manifest.json").read_text())
    led = json.loads((rec / "ledger.json").read_text())
    b = json.loads((rec / "bench.json").read_text())
    cl = json.loads((rec / "check_labels.log").read_text().strip().splitlines()[-1])
    cfg = json.loads((rec / "c2_config.json").read_text())
    agg = json.loads((aud / "aggregate.json").read_text())
    reg = json.loads((aud / "regenerate.json").read_text())
    res = json.loads((aud / "resolve.json").read_text())
    env = json.loads((aud / "environment.json").read_text())
    params = {r["id"]: r["params"] for r in man["instances"]}
    eval_ids = sorted(i for i, r in ((r["id"], r) for r in man["instances"]) if r["split"] == "eval")
    fy = np.array([params[i]["fy"] for i in eval_ids])

    def grid(arm, s, key="abs_curve_err"):
        rows = v["arms"][arm][s]["eval_rows"]
        return np.array([[r[key] for r in rows[i]] for i in eval_ids], dtype=float)

    L = []
    w = L.append
    w(f"<!-- generated by audit/c2_write_verdict.py from records/c2/return and records/c2/audit; config "
      f"{v['config_sha256']} -->")
    w("")

    # ---------------------------------------------------------------- criteria
    w("### Criteria (label-free arm; 64 held-out members at seven levels, 448 pairs a seed)")
    w("")
    w("The distance of a pair from the curve is abs(F / F\\*(e) - 1): F = 4 k_s (D - e) is the spring reading of the "
      "predicted field and F\\*(e) the reference force at its end displacement e.")
    w("")
    w("| Seed | Median distance | 90th percentile | Infinite distances |")
    w("|---|---|---|---|")
    ps = v["per_seed"]
    for i, s in enumerate("012"):
        inf = v["arms"]["label_free"][s]["eval"]["curve_infinite"]
        w(f"| {s} | {pct(ps['abs_curve_err_median'][i], 3)} | {pct(ps['abs_curve_err_p90'][i], 3)} | {inf} |")
    w(f"| **Median over seeds** | **{pct(v['C1_value'], 3)}** (C1: at most 5%) | **{pct(v['C2_value'], 3)}** (C2: at "
      f"most 10%) | |")
    w("")
    w(f"C1 = {v['C1']}; C2 = {v['C2']}; verdict = **{v['verdict']}**. Status of the six runs: "
      + ", ".join(f"{k} {x}" for k, x in v["status"].items()) + f". Missing runs: {len(v['missing'])}; non-finite "
      f"runs: {len(v['non_finite'])}. Recomputed by `audit/c2_recompute.py` from the returned predictions and labels: "
      f"C1 {pct(agg['C1_value'], 3)}, C2 {pct(agg['C2_value'], 3)}, {agg['verdict']}.")
    w("")

    # ---------------------------------------------------------------- every run
    w("### Every arm and seed, held-out pairs (reported)")
    w("")
    w("Medians over the 448 pairs unless marked. Signed errors are prediction over reference, less 1. The force at "
      "the same D is the spring reading against the reference's at that D; the stress reading is the force the "
      "predicted field's stresses carry, against the same reference; the bound is 4 sqrt(2 k_s (Pi - Pi\\*)) over the "
      "reference force; the energy gap is (Pi - Pi\\*) / abs(Pi\\*).")
    w("")
    w("| Run | Distance | Distance, p90 | Signed distance | Above 10% | Infinite | Force at the same D, abs error | "
      "Force at the same D, signed error | End displacement e error | Stress reading error | Energy gap | Bound | "
      "Within bound | Contact overlap | Plastic overlap | Bolt force error | Displacement error | Not evaluated |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for arm, s in RUNS:
        e = v["arms"][arm][s]["eval"]
        A = grid(arm, s)
        w(f"| {name(arm, s)} | {pct(e['abs_curve_err']['median'])} | {pct(e['abs_curve_err']['p90'])} | "
          f"{pct(e['curve_err']['median'], sign=True)} | {int((A > 0.10).sum())} | {e['curve_infinite']} | "
          f"{pct(e['abs_F_err']['median'])} | {pct(e['F_err']['median'], sign=True)} | "
          f"{pct(e['e_err']['median'], sign=True)} | "
          f"{pct(e['F_sigma_err']['median'], sign=True)} | {pct(e['gap']['median'], 2)} | {pct(e['bound']['median'])} | "
          f"{pct(e['within_bound_fraction'], 0)} | {e['iou_contact']['median']:.3f} | {e['iou_plastic']['median']:.3f} | "
          f"{pct(e['bolt_err']['median'], 2, sign=True)} | {pct(e['u_rel_l2']['median'])} | {e['evaluate_failed']} |")
    w("")
    w("The infinite distances, with the note the evaluation wrote (levels in mm):")
    w("")
    for arm, s in RUNS:
        box = v["arms"][arm][s]
        with np.load(rec / "runs" / f"{arm}_s{s}" / "preds.npz") as z:
            e_pred = {iid: z[iid][:, -1].astype(float) for iid in z.files}      # e is the last unknown
        for split, label in (("eval_rows", "held-out"), ("tested", "tested")):
            notes = {}
            for iid, rows in box[split].items():
                for l, r in enumerate(rows):
                    if r["curve_note"]:
                        notes.setdefault(r["curve_note"], []).append((r["D"], e_pred[iid][l], params[iid]["rho"]))
            for note, got in notes.items():
                lv = [x[0] for x in got]
                cnt = {x: lv.count(x) for x in sorted(set(lv))}
                w(f"- {name(arm, s)}, {label}: \"{note}\", {len(lv)} pair{'s' if len(lv) != 1 else ''}: "
                  + ", ".join(f"{n} at {x:g}" for x, n in cnt.items())
                  + f"; predicted end displacement {span([x[1] for x in got], '.4f')} mm, preload ratio "
                  f"{span([x[2] for x in got], '.2f')}.")
    w("")

    # ---------------------------------------------------------------- by level
    w("### The distance by level, held-out members (64 a level)")
    w("")
    head = "| Run | " + " | ".join(f"{x:g} mm" for x in LEVELS) + " |"
    rule = "|---|" + "---|" * len(LEVELS)
    for title, f in (("Median distance", lambda col: pct(quantile(col, 0.5))),
                     ("90th percentile of the distance", lambda col: pct(quantile(col, 0.9))),
                     ("Pairs above 10%", lambda col: str(int((col > 0.10).sum()))),
                     ("Median signed distance", None)):
        w(f"**{title}**")
        w("")
        w(head)
        w(rule)
        for arm, s in RUNS:
            if f is None:
                S = grid(arm, s, "curve_err")
                cells = [pct(quantile(S[:, l], 0.5), sign=True) for l in range(len(LEVELS))]
            else:
                A = grid(arm, s)
                cells = [f(A[:, l]) for l in range(len(LEVELS))]
            w(f"| {name(arm, s)} | " + " | ".join(cells) + " |")
        w("")
    w("**The other readings by level** (medians over the 64 held-out members at each level, over the pairs the "
      "reference code evaluated; the counts are of pairs)")
    w("")
    w("| Run | D (mm) | Force at the same D, signed error | Abs error | Bound | Within bound | End displacement e "
      "error | Stress reading error | Energy gap | Contact overlap | Plastic overlap | Bolt force error | "
      "Displacement error | Infinite distances | Not evaluated |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for arm, s in RUNS:
        rows = v["arms"][arm][s]["eval_rows"]
        for l, D in enumerate(LEVELS):
            at = [rows[i][l] for i in eval_ids]
            assert all(r["D"] == D for r in at)
            md = {k: quantile([r[k] for r in at if not np.isnan(r[k])], 0.5) for k in READ}
            ok = [r for r in at if not r["evaluate_failed"]]
            w(f"| {name(arm, s)} | {D:g} | {pct(md['F_err'], sign=True)} | {pct(md['abs_F_err'])} | "
              f"{pct(md['bound'])} | {sum(r['within_bound'] for r in ok)} of {len(ok)} | "
              f"{pct(md['e_err'], sign=True)} | {pct(md['F_sigma_err'], sign=True)} | {pct(md['gap'], 2)} | "
              f"{md['iou_contact']:.3f} | {md['iou_plastic']:.3f} | {pct(md['bolt_err'], 2, sign=True)} | "
              f"{pct(md['u_rel_l2'])} | {sum(bool(np.isinf(r['curve_err'])) for r in at)} | "
              f"{sum(bool(r['evaluate_failed']) for r in at)} |")
    w("")

    # ---------------------------------------------------------------- yield stress
    lo = fy < FY_SPLIT
    w(f"### The distance at 8 mm and the yield stress (held-out members: {int(lo.sum())} below {FY_SPLIT:g} MPa, "
      f"{int((~lo).sum())} at or above)")
    w("")
    w(f"| Run | Pearson correlation with the yield stress | Median, below {FY_SPLIT:g} MPa | Median, at or above "
      f"{FY_SPLIT:g} MPa |")
    w("|---|---|---|---|")
    for arm, s in RUNS:
        a8 = grid(arm, s)[:, LEVELS.index(8.0)]
        r = f"{np.corrcoef(a8, fy)[0, 1]:+.3f}" if np.all(np.isfinite(a8)) else "not defined"
        w(f"| {name(arm, s)} | {r} | {pct(quantile(a8[lo], 0.5))} | {pct(quantile(a8[~lo], 0.5))} |")
    w("")
    w("**The tail: the pairs above each run's 90th percentile of the distance, and the pairs above 10% at 8 mm**")
    w("")
    w(f"| Run | 90th percentile | Pairs above it | At 6 and 8 mm | At 0.5 and 1 mm | In members below {FY_SPLIT:g} MPa | "
      f"Above 10% at 8 mm | Of them at or above {FY_SPLIT:g} MPa |")
    w("|---|---|---|---|---|---|---|---|")
    lv = np.tile(np.arange(len(LEVELS)), (len(eval_ids), 1))
    low = np.repeat(lo[:, None], len(LEVELS), axis=1)
    for arm, s in RUNS:
        A = grid(arm, s)
        p90 = v["arms"][arm][s]["eval"]["abs_curve_err"]["p90"]
        t = A > p90
        hi8 = A[:, LEVELS.index(8.0)] > 0.10
        w(f"| {name(arm, s)} | {pct(p90)} | {int(t.sum())} | {int((t & (lv >= LEVELS.index(6.0))).sum())} | "
          f"{int((t & (lv <= LEVELS.index(1.0))).sum())} | {int((t & low).sum())} | {int(hi8.sum())} | "
          f"{int((hi8 & ~lo).sum())} |")
    w("")
    top = []
    for s in ("1", "2"):
        a8 = grid("label_free", s)[:, LEVELS.index(8.0)]
        top += [eval_ids[k] for k in np.argsort(-a8, kind="stable")[:5]]
    top = sorted(dict.fromkeys(top), key=lambda i: params[i]["fy"])
    w("**The five largest distances at 8 mm in label-free seeds 1 and 2: the members, by yield stress, and their "
      "distances at every level**")
    w("")
    w("| Member | Yield stress (MPa) | Flange (mm) | Seed | " + " | ".join(f"{x:g} mm" for x in LEVELS) + " |")
    w("|---|---|---|---|" + "---|" * len(LEVELS))
    for iid in top:
        for s in ("1", "2"):
            rows = v["arms"]["label_free"][s]["eval_rows"][iid]
            w(f"| {iid} | {params[iid]['fy']:.1f} | {params[iid]['t_f']:.2f} | {s} | "
              + " | ".join(pct(r["abs_curve_err"]) for r in rows) + " |")
    w("")
    w(f"Yield stresses of the 64 held-out members: {fy.min():.1f} to {fy.max():.1f} MPa.")
    w("")

    # ---------------------------------------------------------------- training and field size
    w("### Training, and the size of the predicted fields (held-out pairs)")
    w("")
    w("| Run | Mean loss, epochs 1 to 20 | Mean loss, epochs 181 to 200 | Loss, epoch 200 | Smallest loss (epoch) | "
      "e / e_ref, median | Norm of the unknowns / label's, median (largest) | Largest predicted unknown in size | "
      "Distinct values predicted |")
    w("|---|---|---|---|---|---|---|---|---|")
    for arm, s in RUNS:
        h = json.loads((rec / "runs" / f"{arm}_s{s}" / "history.json").read_text())
        lo_ = np.asarray(h["loss"], float)
        k = int(np.argmin(lo_))
        ratio = []
        with np.load(rec / "runs" / f"{arm}_s{s}" / "preds.npz") as z:
            allv = np.concatenate([z[i].ravel() for i in eval_ids])
            for iid in eval_ids:
                with np.load(rec / "labels" / f"{iid}.npz") as lab:
                    zr = lab["z"]
                ratio += list(np.linalg.norm(z[iid].astype(float), axis=1) / np.linalg.norm(zr, axis=1))
        e = v["arms"][arm][s]["eval"]
        ratio = np.asarray(ratio)
        lf = (lambda x: f"{x:.4f}" if abs(x) >= 0.01 else f"{x:.3e}")
        w(f"| {name(arm, s)} | {lf(lo_[:20].mean())} | {lf(lo_[-20:].mean())} | {lf(lo_[-1])} | {lf(lo_[k])} ({k + 1}) | "
          f"{1 + e['e_err']['median']:.4f} | {pct(float(np.median(ratio)), 2)} ({pct(float(ratio.max()), 1)}) | "
          f"{float(np.abs(allv).max()):.4g} | {np.unique(allv).size:,} of {allv.size:,} |")
    w("")
    w("The losses are the mean training loss of each epoch (history.json): the energy loss for the label-free arm, the "
      "supervised loss for the supervised arm, so the two arms' losses are not comparable. RUNBOOK_C2.md, section 5, "
      "expects the label-free loss to end at about 10.3 to 10.6 (numbers, not criteria). The norms are those of the "
      "unknown vectors z, prediction against label, at every held-out pair; the largest unknown and the distinct values "
      "are over the predictions for the 64 held-out members.")
    w("")

    # ---------------------------------------------------------------- tested
    w("### The four tested members, every arm and seed (reported, not judged): signed distance from the curve")
    w("")
    w("| Run | Member | " + " | ".join(f"{x:g} mm" for x in LEVELS) + " |")
    w("|---|---|" + "---|" * len(LEVELS))
    for arm, s in RUNS:
        for t in TESTED:
            rows = v["arms"][arm][s]["tested"][t]
            w(f"| {name(arm, s)} | {t[7:]} | " + " | ".join(pct(r["curve_err"], sign=True) for r in rows) + " |")
    w("")
    w("**The tested members overall** (medians over each member's seven levels, and over all 28 tested pairs of the "
      "run)")
    w("")
    w("| Run | Member | Distance | Signed distance | Force at the same D, signed error | Bound | Within bound | End "
      "displacement e error | Stress reading error | Energy gap | Contact overlap | Plastic overlap | Bolt force error "
      "| Displacement error | Infinite distances |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for arm, s in RUNS:
        groups = [(t[7:], v["arms"][arm][s]["tested"][t]) for t in TESTED]
        groups.append(("all four", [r for _, rows in groups for r in rows]))
        for label, rows in groups:
            ok = [r for r in rows if not r["evaluate_failed"]]
            md = {k: quantile([r[k] for r in ok], 0.5) for k in READ}
            w(f"| {name(arm, s)} | {label} | {pct(quantile([r['abs_curve_err'] for r in rows], 0.5))} | "
              f"{pct(quantile([r['curve_err'] for r in rows], 0.5), sign=True)} | {pct(md['F_err'], sign=True)} | "
              f"{pct(md['bound'])} | {sum(r['within_bound'] for r in ok)} of {len(ok)} | {pct(md['e_err'], sign=True)} | "
              f"{pct(md['F_sigma_err'], sign=True)} | {pct(md['gap'], 2)} | {md['iou_contact']:.3f} | "
              f"{md['iou_plastic']:.3f} | {pct(md['bolt_err'], 2, sign=True)} | {pct(md['u_rel_l2'])} | "
              f"{sum(bool(np.isinf(r['curve_err'])) for r in rows)} |")
    w("")
    w("**Every reading of the tested members, by level**")
    w("")
    w("| Run | Member | D (mm) | Signed distance | Force at the same D, signed error | Bound | Within bound | End "
      "displacement e error | Stress reading error | Energy gap | Contact overlap | Plastic overlap | Bolt force error "
      "| Displacement error | Note |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for arm, s in RUNS:
        for t in TESTED:
            for r in v["arms"][arm][s]["tested"][t]:
                if r["evaluate_failed"]:
                    rest = "not evaluated | " * 9
                else:
                    rest = (f"{pct(r['bound'])} | {'yes' if r['within_bound'] else 'no'} | {pct(r['e_err'], sign=True)} | "
                            f"{pct(r['F_sigma_err'], sign=True)} | {pct(r['gap'], 2)} | {r['iou_contact']:.3f} | "
                            f"{r['iou_plastic']:.3f} | {pct(r['bolt_err'], 2, sign=True)} | {pct(r['u_rel_l2'])} | ")
                w(f"| {name(arm, s)} | {t[7:]} | {r['D']:g} | {pct(r['curve_err'], sign=True)} | "
                  f"{pct(r['F_err'], sign=True)} | " + rest + f"{r['curve_note']} |")
    w("")

    # ---------------------------------------------------------------- run record
    w("### Run record")
    w("")
    w(f"- Bench: {b['seconds_per_step_mean']:.4f} s a step on average (median {b['seconds_per_step_median']:.4f}, "
      f"largest {b['seconds_per_step_max']:.4f}) on {len(b['instances'])} training members; {len(b['losses'])} losses, "
      f"all finite: {b['losses_finite']}; peak memory {b['peak_memory_GiB']:.2f} GiB and energies of the training set "
      f"{b['energy_GiB_training_set']:.2f} GiB; predicted training time at most "
      f"{STEPS_ALL * b['seconds_per_step_mean'] / 3600:.1f} h ({STEPS_ALL:,} steps).")
    lab_log = (rec / "label.log").read_text()
    secs = [float(x) for x in re.findall(r" ([\d.]+) s converged$", lab_log, flags=re.M)]
    workers = re.search(r"^workers (\d+)$", lab_log, flags=re.M).group(1)
    lim = cfg["data"]["kkt_limits"]
    w(f"- Labels: {cl['labels']} of {cl['needed']} needed, missing {len(cl['missing'])}, levels as configured: "
      f"{cl['levels_ok']}, every level converged: {cl['converged']}, check ok: {cl['ok']}. {len(secs)} members "
      f"labelled by {workers} worker processes, {min(secs):.1f} s to {max(secs):.1f} s a member; one ledger entry a "
      f"member: {len({e['id'] for e in led}) == len(led) == cl['labels']}; solver: "
      f"{', '.join(sorted({e['solver'] for e in led}))}.")
    w("- Worst optimality residuals over the labels, against their limits: "
      + "; ".join(f"{k} {sci(cl['worst'][k])} ({lim[k][0]} {lim[k][1]:g})" for k in lim)
      + f"; the two force readings (spring and stresses) of every reference agree to {sci(cl['max_F_vs_F_sigma'])} "
      f"(at most 1e-06).")
    starts, ends = {}, {}
    for arm, s in RUNS:
        n = f"{arm}_s{s}"
        att = (rec / "runs" / n / "attempts.log").read_text()
        st = re.findall(r"^(\S+ \S+) CST start$", att, flags=re.M)
        en = re.findall(r"^(\S+ \S+) CST ended: (.+)$", att, flags=re.M)
        starts[n] = [datetime.strptime(x, "%Y-%m-%d %H:%M:%S") for x in st]
        ends[n] = [(datetime.strptime(x, "%Y-%m-%d %H:%M:%S"), y) for x, y in en]
    tt = (rec / "train_times.log").read_text().strip().splitlines()
    t0, t1 = (datetime.strptime(" ".join(x.split()[1:4]) + " " + x.split()[-1], "%b %d %H:%M:%S %Y") for x in tt[1:3])
    w(f"- Training (`train_times.log`, host {tt[0]}): from {t0:%d %B %Y %H:%M:%S} to {t1:%d %B %Y %H:%M:%S} CST "
      f"(UTC+8), {(t1 - t0).total_seconds() / 3600:.2f} h.")
    w("")
    w("| Run | Attempts | Started (CST) | Ended (CST) | Hours | Status | Steps | Seconds per epoch, median (range) | "
      "Seconds per step, median epoch | Peak memory (GiB) | Losses finite |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for arm, s in RUNS:
        n = f"{arm}_s{s}"
        h = json.loads((rec / "runs" / n / "history.json").read_text())
        es = np.asarray(h["epoch_seconds"], float)
        spe = h["steps"] / len(es)
