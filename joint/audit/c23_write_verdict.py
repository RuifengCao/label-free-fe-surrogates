def recomputation(w, v, aud: pathlib.Path) -> None:
    """The author's recomputation, from the files that audit/c23_recompute.py wrote; a file that is not there is
    left out."""
    if not (aud / "aggregate.json").exists():
        return
    agg = json.loads((aud / "aggregate.json").read_text())
    w("### The author's recomputation (`audit/c23_recompute.py`, records in `records/c23/audit/`)")
    w("")
    # every step's environment, from the record that the step wrote
    steps = (("records.json", "the records"), ("regenerate.json", "the instances"),
             ("environment_curves.json", "the pairs in another order"), ("environment_fields.json", "the fields"),
             ("environment_host_label_free.json", "the pairs in the gate's order (label-free arm)"),
             ("environment_host_supervised_512.json", "the pairs in the gate's order (supervised arm)"),
             ("resolve.json", "the re-solved members"), ("resolve_train.json", "the re-solved training members"),
             ("aggregate.json", "the last step"))
    envs = {}
    for name, what in steps:
        if (aud / name).exists():
            e = json.loads((aud / name).read_text())
            envs[what] = e.get("environment", e)
    if envs:
        same = {k: sorted({str(e[k]) for e in envs.values()}) for k in ("python", "scipy", "solver", "cpus", "blas_threads_env")}
        by_numpy = {}
        for what, e in envs.items():
            by_numpy.setdefault(e["numpy"], []).append(what)
        w("- Environment, from the record of each step: Python " + ", ".join(same["python"]) + ", scipy "
          + ", ".join(same["scipy"]) + ", solver " + ", ".join(same["solver"]) + ", " + ", ".join(same["cpus"])
          + " processors, BLAS threads a process " + ", ".join(same["blas_threads_env"]) + "; "
          + "; ".join(f"numpy {n} for " + ", ".join(ws) for n, ws in sorted(by_numpy.items())) + ".")
    if (aud / "regenerate.json").exists():
        reg = json.loads((aud / "regenerate.json").read_text())
        r2 = reg["environment"]
        w(f"- Regenerated instances (`regenerate.json`; zlib {r2['zlib']}, archive creator field {reg['zip_creator']}): "
          f"{reg['sha256_equal']} of {reg['files']} files have the manifest's SHA-256 and {reg['sizes_equal']} its sizes; the "
          f"members are the configured draws: {reg['members_are_the_configured_draws']}; members shared between two sets: "
          f"{sum(reg['members_shared_between_sets'].values())}.")
    w(f"- From the returned per-pair rows, with the script's own quantile and its own code for part 1 (`aggregate.json`): "
      f"largest relative difference of a statistic from the returned one "
      f"{sci(agg['statistics_largest_relative_difference_from_returned'])}; the wording of part 2 equal: "
      f"{agg['part2']['wording_equal']}; the verdict and the ranking of part 1 equal: {agg['part1']['equal_to_returned_words']}; "
      f"every reported block of part 1 equal: {agg['part1']['all_blocks_equal_to_returned']}; the identity values within the "
      f"tolerance: {agg['identity']['ok']}.")
    f = agg["fields"]
    if f["members"]:
        w(f"- Metrics that need no solve, recomputed for {f['fields']:,} fields of {f['members']} members (members not "
          f"recomputed: {len(f['members_missing'])}): largest absolute difference from the returned rows "
          + ", ".join(f"{k} {sci(x)}" for k, x in f["max_abs_diff"].items())
          + f"; containment in the bound differing in {f['within_bound_mismatches']} fields.")
    if "label_check" in agg:
        lc = agg["label_check"]
        w(f"- The returned labels on the regenerated instances, {lc['levels']} levels: largest relative difference in energy "
          f"{sci(lc['Pi_rel'])}, in force {sci(lc['F_rel'])}; in end displacement {sci(lc['e_diff'])} mm; largest "
          f"unconstrained residual {sci(lc['res_unconstrained'])}; smallest gap {sci(lc['min_gap'])}; smallest multiplier "
          f"{sci(lc['min_lambda'])}.")
    if "condensed_from_parts" in agg:
        cp = agg["condensed_from_parts"]
        w(f"- The condensed fields from the returned base fields, raw fields and amplitudes, in float32, for "
          f"{cp['member_run_pairs']} member and run pairs: largest absolute difference {sci(cp['max_abs_diff'])} "
          f"({cp['unknowns_differing']} unknowns differ; the largest unknown is {cp['max_abs_field']:.3g} in size).")
    for key, title in (("host_order", "in the order of the gate's own evaluation"),
                       ("curves", "in another order (one reading at a time)")):
        cv = agg.get(key)
        if not cv or not cv["pairs"]:
            continue
        w(f"- The error with its exact solve, recomputed {title} for {cv['pairs']:,} pairs ({cv['seconds'] / 3600:.2f} "
          f"processor hours): largest absolute difference of the signed error from the returned one "
          f"{sci(cv['max_abs_diff']['curve_err']) if math.isfinite(cv['max_abs_diff']['curve_err']) else 'infinite (see the table)'}"
          + ("; largest absolute difference of the other metrics "
             + sci(max(x for k, x in cv["max_abs_diff"].items() if k != "curve_err")) + "."))
        w("")
        w("| Reading, set, run | Pairs recomputed | Largest absolute difference of the error | Infinite as returned | "
          "Infinite as recomputed |")
        w("|---|---|---|---|---|")
        for k, g in sorted(cv["by_reading_set_run"].items()):
            d = g["max_abs_diff_curve_err"]
            w(f"| {k.replace('|', ', ')} | {g['pairs']} | {sci(d) if math.isfinite(d) else 'infinite'} | "
              f"{g['infinite_returned']} | {g['infinite_recomputed']} |")
        w("")
        if key == "host_order":
            for n in cv["pairs_with_a_note"]:
                w(f"- A row with a note in the gate's order: {n['id']}, {n['run']}, {n['reading']}, {LEVELS[n['level']]:g} mm: "
                  f"recomputed {pct(n['recomputed'][0], 2, True)} ({n['recomputed'][1] or 'no note'}), returned "
                  f"{pct(n['returned'][0], 2, True)} ({n['returned'][1] or 'no note'}).")
            st = agg.get("statistics_from_host_order") or {}
            done = {k: b for k, b in st.items() if b}
            if done:
                w("- From the errors recomputed in the gate's order, where every pair of an arm's reading on the third sample "
                  "was recomputed: largest relative difference of a run's median or 90th percentile from the returned one "
                  + ", ".join(f"{k.replace('|', ' ')} {sci(b['largest_relative_difference_from_returned'])}"
                              for k, b in sorted(done.items())) + ".")
            for name, title2 in (("part2_from_host_order", "the judged ratios"),
                                 ("side_ratios_from_host_order", "the ratios with the supervised arm read raw")):
                b = agg.get(name)
                if b:
                    a = b["against_returned"]
                    w(f"- From the same errors, {title2}: {b['ratio_of_medians']:.4f} and {b['ratio_of_p90']:.4f}, wording "
                      f"\"{b['wording']}\"; relative difference from the returned ones {sci(a['ratio_of_medians'])} and "
                      f"{sci(a['ratio_of_p90'])}; wording equal: {a['wording_equal']}.")
        name = "part1_from_host_order" if key == "host_order" else "part1_from_recomputed_curves"
        b = agg.get(name)
        if b:
            a = b["against_returned"]
            w(f"- Part 1 from the errors recomputed {title}: {b['flagged']} of {b['pairs']} pairs flagged; pairs not flagged "
              f"above 10% in some run {b['not_flagged_pairs_above_0.10_in_any_run']}; readings above 5% among those not "
              f"flagged {b['not_flagged_readings_above_0.05']} of {b['not_flagged_readings']}; S1 {b['S1']}, S2 {b['S2']}, "
              f"S3 {b['S3']}: {b['verdict']}; R " + ", ".join(f"{x:.3f}" for x in b["auc_above_0.05"]) + f": {b['R']}. "
              f"Equal to the returned part 1 in every count and word: {a['all_equal']}; the flags equal: {a['flags_equal']}.")
    two = agg.get("two_orders")
    if two and two["pairs_in_both"]:
        w(f"- Pairs recomputed in both orders: {two['pairs_in_both']:,}. Where both errors are finite, their largest absolute difference is "
          f"{sci(two['max_abs_diff_curve_err_where_both_finite'])}. Finite in one order only: "
          + ("none" if not two["finite_in_one_only"] else "; ".join(
              f"{n['id']}, {n['run']}, {n['reading']}, {LEVELS[n['level']]:g} mm (the other order: {pct(n['other_order'][0], 2, True)}, "
              f"{n['other_order'][1] or 'no note'}; the gate's order: {pct(n['gates_order'][0], 2, True)})"
              for n in two["finite_in_one_only"])) + ".")
    for name, what in (("resolve.json", "Held-out and tested members"), ("resolve_train.json", "Training members")):
        if (aud / name).exists():
            res = json.loads((aud / name).read_text())
            w(f"- {what} re-solved from the regenerated instances (`{name}`): " + "; ".join(
                f"{r['id']}: bit for bit {r['bit_identical']}, largest difference {sci(r['max_z_diff_over_max_z'])} of the "
                f"largest unknown, {sci(r['max_Pi_rel'])} in energy, {sci(r['max_F_rel'])} in force, iterations equal to the "
                f"ledger's {r['iterations'] == r['ledger_iterations']}, converged {all(r['converged'])}" for r in res["members"]) + ".")


