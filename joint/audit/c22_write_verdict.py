def quantile(v, q: float) -> float:
    s = sorted(float(x) for x in v)
    h = (len(s) - 1) * q
    lo = math.floor(h)
    t = h - lo
    a, b = s[lo], s[min(lo + 1, len(s) - 1)]
    if t == 0 or a == b:
        return a
    if math.isinf(a) or math.isinf(b):
        return b
    return a + (b - a) * t


def pct(x, d=2, sign=False):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    if math.isinf(x):
        return "infinite"
    return f"{100 * x:+.{d}f}%" if sign else f"{100 * x:.{d}f}%"


def sci(x):
    return "0" if x == 0 else f"{x:.1e}"


