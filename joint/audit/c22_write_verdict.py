    w("")
    w("| Reading | Seed | Median, below | 90th percentile, below | Above 10%, below | Median, at or above | "
      "90th percentile, at or above | Above 10%, at or above |")
    w("|---|---|---|---|---|---|---|---|")
    for reading in READINGS:
        for seed in SEEDS:
            a, b = errs(reading, seed, "eval", 6, ids=lo), errs(reading, seed, "eval", 6, ids=hi)
            w(f"| {reading} | {seed} | {pct(quantile(a, 0.5))} | {pct(quantile(a, 0.9))} | {sum(x > 0.10 for x in a)} | "
              f"{pct(quantile(b, 0.5))} | {pct(quantile(b, 0.9))} | {sum(x > 0.10 for x in b)} |")
    w("")
    w("### The pairs above 10% in the condensed reading, by member and level")
    w("")
    w("Signed distances of seeds 5, 6 and 7; a pair is listed if any seed is above 10% in the condensed reading.")
    w("")
    for s in ("eval", "former"):
        w(f"**{SET_TITLE[s]}**")
        w("")
        w("| Member | $t_f$ (mm) | $f_y$ (MPa) | $w$ (mm) | $n$ (mm) | Level | Condensed, seeds 5, 6, 7 | Raw, seeds 5, 6, 7 | "
          "Amplitude, seeds 5, 6, 7 |")
        w("|---|---|---|---|---|---|---|---|---|")
        amp = {seed: json.loads((rec / "run_files" / f"label_free_s{seed}" / "condense.json").read_text())["members"]
               for seed in SEEDS}
        n_pairs, members = 0, set()
