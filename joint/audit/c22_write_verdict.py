    cv = agg["curves"]
    w(f"- The judged error with its exact solve, recomputed for {cv['pairs']} pairs ({cv['seconds'] / 3600:.2f} processor "
      f"hours): largest absolute difference of the signed distance from the returned one {sci(cv['max_abs_diff']['curve_err'])}.")
