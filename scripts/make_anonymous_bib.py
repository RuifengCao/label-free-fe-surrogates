"""Write paper/statics/references_anonymous.bib, the bibliography of the review copies of the
statics paper for the journal's double-anonymized review (main.tex, supplementary.tex).

It is references.bib with the entries of the authors' own note and of their three archives
(code, trained networks, data sets) replaced by anonymous entries under the same keys, so
that the text, the citations and their numbering are those of the paper, and the reference
list names neither the authors nor an address from which they can be found.

usage: python scripts/make_anonymous_bib.py            (writes the file)
       python scripts/make_anonymous_bib.py --check    (exits 1 if the file differs)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "paper" / "statics" / "references.bib"
OUT = ROOT / "paper" / "statics" / "references_anonymous.bib"

OMITTED = "Details omitted for double-anonymized reviewing"
# the authors' note, and the three archives, data references with "[dataset]" before them
# as in references.bib
OWN = {
    "CaoSong2026": "Anonymous",
    "Cao2026Zenodo": r"{\relax [dataset] A}nonymous",
    "Cao2026Networks": r"{\relax [dataset] A}nonymous",
    "Cao2026Data": r"{\relax [dataset] A}nonymous",
}
HEADER = (
    "% Generated by scripts/make_anonymous_bib.py from references.bib; do not edit.\n"
    "% The bibliography of the review copies for double-anonymized review: the entries of the\n"
    "% authors' own note and archives are anonymous, under the same keys; every other entry\n"
    "% is that of references.bib.\n\n")


def anonymous(src: str) -> str:
    out = src
    for key, author in OWN.items():
        pat = re.compile(r"@misc\{" + re.escape(key) + r",\n.*?\n\}", re.S)
        if len(pat.findall(out)) != 1:
            raise SystemExit(f"references.bib: the entry {key} is not found once")
        entry = (f"@misc{{{key},\n  author = {{{author}}},\n  title  = {{{OMITTED}}},\n"
                 f"  year   = {{2026}}\n}}")
        out = pat.sub(lambda m: entry, out)
    return HEADER + out


def main() -> int:
    text = anonymous(SRC.read_text(encoding="utf-8"))
    if sys.argv[1:] == ["--check"]:
        same = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print("references_anonymous.bib " + ("is current" if same else "differs"))
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
